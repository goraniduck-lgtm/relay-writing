const A = { uid: 'tabA' }, B = { uid: 'tabB' }, X = { uid: 'other' };
let pass = 0, failN = 0;
function check(name, fn, ok) { let r = true, err = ''; try { fn(); } catch (e) { r = false; err = e.message; } if (r === ok) pass++; else { failN++; console.log('✗', name, ok ? '(거절됨: ' + err + ')' : '(허용됨)'); } }
