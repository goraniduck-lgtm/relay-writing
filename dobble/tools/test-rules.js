deny('참가자 아닌 C가 기록', () => db.set(U('c'), M + 'claims/0/c', 100));
deny('B가 D 자리로 판 가져가기', () => db.set(U('b'), M + 'claims/1/d', 800));
allow('B가 1번 판', () => db.set(U('b'), M + 'claims/1/b', 800));
allow('D 나감 표시', () => db.update(U('d'), M.slice(0, -1), { 'quit/d': true, 'on/d': null }));
