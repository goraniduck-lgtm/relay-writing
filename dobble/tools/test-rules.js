allow('B 들어가기', () => db.set(U('b'), M + 'seats/b', 'tabB'));
allow('C 들어가기', () => db.set(U('c'), M + 'seats/c', 'tabC'));
deny('D가 C 자리 빼앗기', () => db.set(U('d'), M + 'seats/c', 'tabD'));
allow('D 들어가기', () => db.set(U('d'), M + 'seats/d', 'tabD'));
deny('E 들어가기 (4명 방이라 e 자리 없음)', () => db.set(U('e'), M + 'seats/e', 'tabE'));
deny('이상한 자리 g', () => db.set(U('e'), M + 'seats/g', 'tabE'));
deny('인원 바꾸기', () => db.set(A, M + 'cfg/max', 6));
allow('C 별명', () => db.set(U('c'), M + 'names/c', '초록이'));
deny('C가 D 별명', () => db.set(U('c'), M + 'names/d', '바보'));
