deny('X가 2번 자리 빼앗기', () => db.set(X, R + '1234/seats/b', 'other'));
deny('X가 1번 자리 바꾸기', () => db.set(X, R + '1234/seats/a', 'other'));
deny('A가 1번 자리를 남에게', () => db.set(A, R + '1234/seats/a', 'other'));
deny('3번 자리 만들기', () => db.set(X, R + '1234/seats/c', 'other'));
allow('B 별명', () => db.set(B, R + '1234/names/b', '토끼'));
deny('B가 A 별명 바꾸기', () => db.set(B, R + '1234/names/a', '바보'));
deny('너무 긴 별명', () => db.set(B, R + '1234/names/b', '아주아주아주긴별명입니다'));
allow('B 접속 표시', () => db.set(B, R + '1234/on/b', true));
deny('B가 A 접속 표시', () => db.set(B, R + '1234/on/a', true));
allow('B 접속 표시 지우기', () => db.set(B, R + '1234/on/b', null));

deny('X가 B 자리 비우기', () => db.set(X, R + '1234/seats/b', null));
allow('기다리는 방: B가 나가기', () => db.update(B, R + '1234', { 'names/b': null, 'seats/b': null, 'on/b': null }));
allow('B가 다시 들어오기', () => db.set(B, R + '1234/seats/b', 'tabB'));
deny('시작 전 판 가져가기', () => db.set(A, R + '1234/claims/0/a', 800));
deny('X가 시작', () => db.update(X, R + '1234/cfg', { st: 'play', go: db.now }));
deny('이상한 상태', () => db.update(B, R + '1234/cfg', { st: 'end' }));
deny('너무 먼 시작 시각', () => db.update(B, R + '1234/cfg', { st: 'play', go: db.now + 3600e3 }));
allow('B가 시작 (3초 뒤)', () => db.update(B, R + '1234/cfg', { st: 'play', go: db.now + 3600 }));
deny('카운트다운 중 판 가져가기', () => db.set(A, R + '1234/claims/0/a', 800));
db.now += 4000;
deny('X가 판 가져가기', () => db.set(X, R + '1234/claims/0/a', 800));
deny('A가 B 자리로 판 가져가기', () => db.set(A, R + '1234/claims/0/b', 800));
deny('이상한 자리 값', () => db.set(A, R + '1234/claims/0/c', 800));
deny('반응 시간이 숫자 아님', () => db.set(A, R + '1234/claims/0/a', 'fast'));
deny('반응 시간 음수', () => db.set(A, R + '1234/claims/0/a', -5));
deny('판 번호가 숫자 아님', () => db.set(A, R + '1234/claims/x/a', 800));
deny('옛 방식(글자) 판 기록', () => db.set(A, R + '1234/claims/0', 'a'));
allow('A 0번 판 기록 (900ms)', () => db.set(A, R + '1234/claims/0/a', 900));
deny('A 기록 바꾸기', () => db.set(A, R + '1234/claims/0/a', 100));
allow('B 0번 판 기록 (700ms, 늦게 도착했지만 더 빠름)', () => db.set(B, R + '1234/claims/0/b', 700));
deny('X가 확정', () => db.update(X, R + '1234/claims/0', { win: 'b' }));
deny('확정하면서 기록 바꾸기', () => db.set(A, R + '1234/claims/0', { a: 100, b: 700, win: 'a' }));
deny('기록 없는 자리로 확정', () => db.set(A, R + '1234/claims/0', { a: 900, b: 700, win: 'c' }));
allow('A가 B를 이긴 자리로 확정', () => db.set(A, R + '1234/claims/0', { a: 900, b: 700, win: 'b' }));
deny('확정 바꾸기', () => db.set(B, R + '1234/claims/0', { a: 900, b: 700, win: 'a' }));
deny('확정 뒤 늦은 기록', () => db.set(U('x'), R + '1234/claims/0/a', 1));
deny('게임 중에는 B 자리 비우기 안 됨', () => db.set(B, R + '1234/seats/b', null));
deny('X가 나감 표시', () => db.set(X, R + '1234/quit/a', true));
