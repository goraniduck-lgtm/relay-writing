deny('게임 중 새 자리 앉기', () => db.set(X, M + 'seats/e', 'other'));
deny('게임 중 C 자리 비우기', () => db.set(U('c'), M + 'seats/c', null));
deny('참가자가 아닌 C가 판 가져가기', () => db.set(U('c'), M + 'claims/0/c', 800));
