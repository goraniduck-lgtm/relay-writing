allow('C 다시 들어오기', () => db.set(U('c'), M + 'seats/c', 'tabC'));
deny('참가자 목록 이상 (순서 뒤집힘)', () => db.update(U('d'), M + 'cfg', { st: 'play', go: db.now - 1, players: 'dcba', n: 28 }));
