deny('인원 1명 방', () => db.set(A, R + '4321', big(1)));
deny('처음부터 c 자리 채우기', () => db.set(A, R + '4321', big(4, { seats: { a: 'tabA', c: 'tabC' } })));
deny('처음부터 시작한 방', () => db.set(A, R + '4321', big(4, { cfg: { set: 'basic', n: 42, per: 6, max: 4, seed: 9, st: 'play' } })));
